"""Runs the experiments of README.md and writes results/experiments.md and
results/experiments.json.

Each cell is `total s / requests / overfetch` for all four traces of a
slide (overview, zoom, pan_L0, pan_mid), where total s is the sum of the
modelled time-to-complete of every view, requests the number of HTTP
requests, and overfetch the bytes fetched over the bytes of the intervals
that lie under the visible regions (what any reader must fetch).

Usage: uv run python experiments/ndpi_access/run_experiments.py
"""

from __future__ import annotations

import dataclasses
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import bench  # noqa: E402
import model as m  # noqa: E402

OUT = Path(__file__).parent / "results"
SLIDES = ["CMU-1", "Hamamatsu-1"]
NETS = ["h1-20ms-50M", "h1-80ms-50M", "h1-20ms-500M", "h1-80ms-500M", "h2-20ms-50M", "h2-80ms-500M",
        "openslide"]
TRACES = ["overview", "zoom", "pan_L0", "pan_mid"]

EXPERIMENTS = [
    ("E0", "Baseline and lower bound", False,
     ["spec:pc64k", "spec:ideal", "interval:ideal"]),
    ("E1", "Per-reference merge gap (what a reader can do alone)", False,
     ["spec:pc2", "spec:pc64k", "spec:pc256k", "spec:pc1m", "spec:pcbdp", "spec:pcbdpc"]),
    ("E2", "Cross-chunk batching (a view's chunk reads planned together)", False,
     ["spec:b2", "spec:b64k", "spec:bbdp", "spec:bbdpc", "spec:bopt"]),
    ("E3", "Caches shared across chunks and views", False,
     ["spec:blk64k", "spec:blk64kj", "spec:blk1m", "spec:row", "spec:pc64k+c", "spec:b2+c",
      "spec:bbdpc+c", "spec:bopt+c"]),
    ("E4", "HTTP multi-range requests (hosts that answer them)", True,
     ["spec:mrpc", "spec:mr", "spec:mr+c", "spec:mrbdpc+c", "spec:bopt+c", "spec:ideal"]),
    ("E5", "Chunk shape (a spec change), per-reference reader of today", False,
     [f"{c}:pc64k" for c in m.CHUNKINGS if c != "interval"]),
    ("E6", "Chunk shape (a spec change), batched cost-model reader with span cache", False,
     [f"{c}:bopt+c" for c in m.CHUNKINGS if c != "interval"]),
    ("E7", "Chunk shape with multi-range or HTTP/2-style exact reads", True,
     [f"{c}:mr+c" for c in ("spec", "w4096x256", "w8192x128", "adaptive_wide")]),
]


def main() -> None:
    OUT.mkdir(exist_ok=True)
    slides = {s: m.load(s) for s in SLIDES}
    traces = {s: m.traces(sl) for s, sl in slides.items()}
    md = ["# NDPI access experiments\n",
          "Generated by `run_experiments.py`. Cell: `total s / requests / overfetch` over all 4 traces "
          "(56 views), overfetch relative to the bytes of the intervals under the visible regions; "
          "`px` is decoded over visible pixels.\n"]
    nets_md = " | ".join(m.NETS[n].name for n in NETS)
    js = []
    for eid, title, multirange, specs in EXPERIMENTS:
        md.append(f"\n## {eid}. {title}\n")
        for sname, slide in slides.items():
            md.append(f"\n### {sname}\n")
            md.append(f"| strategy | px | {nets_md} |")
            md.append("|---|---:|" + "---:|" * len(NETS))
            for spec in specs:
                cname, pname = spec.split(":")
                cells, px = [], 0.0
                for nname in NETS:
                    # openslide.cs.cmu.edu answers multi-range requests with one range
                    # (probe_hosts.py): multi-range planners fall back to single ranges
                    net = dataclasses.replace(m.NETS[nname], multirange=multirange and nname != "openslide")
                    rows = []
                    for t in TRACES:
                        rows += bench.run_trace(slide, m.CHUNKINGS[cname], traces[sname][t],
                                                bench.PLANNERS[pname](), net)
                    s = bench.summarize(rows)
                    px = s["px_overdecode"]
                    cells.append(f"{s['total_s']:.1f} / {s['requests']} / {s['overfetch_visible']:.1f}")
                    js.append({"experiment": eid, "slide": sname, "net": nname, "multirange": multirange,
                               "chunking": cname, "planner": pname, **s})
                label = f"{m.CHUNKINGS[cname].name} + {bench.PLANNERS[pname]().name}"
                md.append(f"| {label} | {px:.2f} | " + " | ".join(cells) + " |")
                print(md[-1], flush=True)
    (OUT / "experiments.md").write_text("\n".join(md) + "\n")
    (OUT / "experiments.json").write_text(json.dumps(js, indent=1))


if __name__ == "__main__":
    main()
